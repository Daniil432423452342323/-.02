"""Расширенное тестирование алгоритма скидки для 27-го варианта."""
from datetime import datetime
from discount import calculate_price_with_discount

def print_test_report(passed, total):
    """Домашнее задание №2: Функция вывода официального отчета."""
    print("\n" + "=" * 40)
    print("ОТЧЁТ О ТЕСТИРОВАНИИ")
    print(f"Пройдено: {passed} / {total}")
    if passed == total:
        print("Результат: ✅ УСПЕХ")
    else:
        print("Результат: ❌ ЕСТЬ ОШИБКИ")
    print("=" * 40 + "\n")

def run_tests():
    """Прогон расширенных и граничных тест-кейсов."""
    test_cases = [
        # Позитивные тесты (из прошлой работы)
        (1, 1000, datetime(2026, 10, 15), 1000, "Задача 1: есть назначения в сентябре"),
        (2, 2000, datetime(2026, 10, 15), 2000, "Задача 2: есть назначения в сентябре"),
        (4, 4000, datetime(2026, 10, 15), 3000, "Задача 4: нет назначений ➔ скидка 25%"),
        
        # Граничные тесты (Задание 4.1 и Домашнее задание)
        (1, 1000, datetime(2026, 10,  1), 1000, "Граничный случай: 1-е число месяца (проверка сентября)"),
        (2, 2000, datetime(2026, 10, 31), 2000, "Граничный случай: последний день месяца (проверка сентября)"),
        (4, 4000, datetime(2026, 10,  1), 3000, "Граничный случай: 1-е число месяца без назначений ➔ скидка"),
        
        # Смена периодов проверки (Проверяем октябрь 2026 года)
        # В вашей базе в октябре нет назначений, поэтому все задачи в ноябре должны получить скидку!
        (1, 1000, datetime(2026, 11, 15), 750,  "Проверка ноября: в октябре назначений нет ➔ скидка 25%"),
        (2, 2000, datetime(2026, 11, 15), 1500, "Проверка ноября: в октябре назначений нет ➔ скидка 25%"),
        
        # Граничный случай с ценой (Товар с нулевой стоимостью)
        (5, 0,    datetime(2026, 10, 15), 0,    "Граничный случай: задача с нулевой базовой ценой"),
    ]
    
    print("=" * 75)
    print("РАСШИРЕННОЕ И ГРАНИЧНОЕ ТЕСТИРОВАНИЕ АЛГОРИТМА СКИДКИ")
    print("=" * 75)
    passed = 0
    
    for task_id, price, date, expected, comment in test_cases:
        result = calculate_price_with_discount(task_id, price, date)
        status = "✅" if result == expected else "❌"
        if result == expected:
            passed += 1
        print(f"{status} Задача №{task_id} на {date.date()}: {price} руб. ➔ {result} руб. | {comment}")
        
    print("=" * 75)
    
    # Вызов функции генерации отчёта
    print_test_report(passed, len(test_cases))

if __name__ == "__main__":
    run_tests()
